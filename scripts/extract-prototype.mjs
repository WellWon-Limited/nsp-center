/**
 * Read-only extraction of the supplied prototype's JSON data islands.
 * No artifact JavaScript is imported, evaluated or executed.
 * Run: node scripts/extract-prototype.mjs [--check]
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { gunzipSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
assert(process.argv.slice(2).every((arg) => arg === '--check'), 'Only --check is supported');
const inputPath = 'assets/NSP App Prototype.html';
const bytes = await readFile(resolve(root, inputPath));
const bundled = bytes.toString('utf8');
const sha256 = (data) => createHash('sha256').update(data).digest('hex');
const json = (data) => `${JSON.stringify(data, null, 2)}\n`;
const island = (name) => {
  const matches = [...bundled.matchAll(new RegExp(`<script\\b[^>]*type=["']__bundler/${name}["'][^>]*>([\\s\\S]*?)</script>`, 'g'))];
  assert.equal(matches.length, 1, `Expected one ${name} JSON island`);
  return JSON.parse(matches[0][1]);
};
const manifest = island('manifest');
const template = island('template');
assert.equal(typeof template, 'string');
assert.equal(typeof manifest, 'object');
assert.equal(island('page_order').length, 0, 'Nested pages require an explicit extraction policy');

const decoded = new Map();
for (const [id, item] of Object.entries(manifest)) {
  assert.match(id, /^[a-f\d-]{36}$/i);
  assert.equal(typeof item.mime, 'string');
  assert.equal(typeof item.data, 'string');
  assert.equal(typeof item.compressed, 'boolean');
  assert.match(item.data, /^[A-Za-z\d+/]*={0,2}$/);
  assert(item.data.length < 16 * 1024 * 1024, 'Resource exceeds extraction limit');
  const packed = Buffer.from(item.data, 'base64');
  const data = item.compressed ? gunzipSync(packed, { maxOutputLength: 16 * 1024 * 1024 }) : packed;
  decoded.set(id, { mime: item.mime, data, compressed: item.compressed });
}

const output = new Map();
const referencePath = 'design/systems/nsp/source';
// Reference text lives outside public/ and is never loaded by the application.
output.set(`${referencePath}/prototype.template.html`, template);
const sourceStyles = [...template.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/g)].map((match) => match[1]);
output.set(`${referencePath}/prototype.styles.css`, `${sourceStyles.join('\n\n')}\n`);
const component = template.match(/<script\b[^>]*type="text\/x-dc"[^>]*>([\s\S]*?)<\/script>/);
assert(component, 'Prototype component source is missing');
output.set(`${referencePath}/prototype.component.txt`, component[1]);

const fontCss = [];
const fonts = [];
const seenFonts = new Map();
for (const match of sourceStyles.join('\n').matchAll(/\/\*\s*([\w-]+)\s*\*\/\s*(@font-face\s*\{[^}]+\})/g)) {
  const subset = match[1];
  const block = match[2];
  const family = block.match(/font-family:\s*'([^']+)'/)?.[1];
  const weight = block.match(/font-weight:\s*(\d+)/)?.[1];
  const id = block.match(/src:\s*url\("([a-f\d-]+)"\)/)?.[1];
  assert(family === 'Manrope' || family === 'IBM Plex Mono', 'Unexpected font family');
  assert(id && weight && decoded.get(id)?.mime === 'font/woff2', 'Invalid bundled font');
  // The supplied Manrope files are variable fonts; 400–800 are the weights
  // explicitly declared in the prototype. The same subset bytes are reused.
  const range = family === 'Manrope' ? '400 800' : weight;
  const key = `${family}/${subset}/${range}`;
  if (seenFonts.has(key)) {
    assert.equal(seenFonts.get(key), id, 'Weights no longer share the same Manrope subset');
    continue;
  }
  seenFonts.set(key, id);
  const filename = `${family.toLowerCase().replaceAll(' ', '-')}-${family === 'Manrope' ? '' : `${weight}-`}${subset}.woff2`;
  const path = `public/prototype/fonts/${filename}`;
  const data = decoded.get(id).data;
  assert.equal(data.subarray(0, 4).toString(), 'wOF2', 'Invalid WOFF2 signature');
  output.set(path, data);
  fontCss.push(`/* ${subset} — bytes from the supplied prototype */\n${block.replace(`font-weight: ${weight};`, `font-weight: ${range};`).replace(`url("${id}")`, `url("/prototype/fonts/${filename}")`)}`);
  fonts.push({ family, weight: range, subset, resourceId: id, path, bytes: data.length, sha256: sha256(data) });
}
assert.equal(fonts.length, 16, 'Prototype font set changed; review extraction before updating');
output.set('design/systems/nsp/fonts.css', `/* Generated by scripts/extract-prototype.mjs. Do not edit. */\n${fontCss.join('\n\n')}\n`);
for (const slug of ['manrope', 'ibmplexmono']) {
  const license = await readFile(resolve(root, `design/systems/nsp/licenses/${slug}-OFL.txt`));
  assert(license.toString().includes('SIL OPEN FONT LICENSE'));
  output.set(`public/prototype/fonts/${slug}-OFL.txt`, license);
}
const images = [...decoded.entries()].filter(([, item]) => item.mime.startsWith('image/'));
assert.equal(images.length, 1, 'Expected the prototype’s single supplied image');
assert.equal(images[0][1].mime, 'image/png');
assert.equal(images[0][1].data.subarray(0, 8).toString('hex'), '89504e470d0a1a0a');
output.set('public/prototype/sets.png', images[0][1].data);

const count = (values) => Object.fromEntries([...values.reduce((map, value) => map.set(value, (map.get(value) ?? 0) + 1), new Map())].sort(([a], [b]) => a.localeCompare(b)));
const inlineStyles = [...template.matchAll(/\bstyle="([^"]*)"/g)].map((match) => match[1]);
const declarations = {};
for (const style of inlineStyles) {
  for (const declaration of style.split(';')) {
    const colon = declaration.indexOf(':');
    if (colon === -1) continue;
    const property = declaration.slice(0, colon).trim();
    const value = declaration.slice(colon + 1).trim();
    (declarations[property] ??= []).push(value);
  }
}
output.set(`${referencePath}/inventory.json`, json({
  description: 'Literal source values; includes dynamic {{ }} expressions and presentation-only phone chrome.',
  inlineStyleCount: inlineStyles.length,
  colors: count([...template.matchAll(/#[\da-f]{3,8}\b/gi)].map((match) => match[0])),
  alphaColors: count([...template.matchAll(/rgba?\([^)]+\)/g)].map((match) => match[0])),
  declarations: Object.fromEntries(Object.entries(declarations).sort(([a], [b]) => a.localeCompare(b)).map(([property, values]) => [property, count(values)])),
}));
output.set(`${referencePath}/provenance.json`, json({
  input: inputPath, sha256: sha256(bytes), templateSha256: sha256(template),
  extraction: 'JSON.parse of data islands, strict Base64 decode, bounded gzip inflate; no artifact code execution.',
  resources: [...decoded.entries()].map(([id, item]) => ({ id, mime: item.mime, compressed: item.compressed, bytes: item.data.length, sha256: sha256(item.data), exported: item.mime === 'font/woff2' || item.mime === 'image/png' })),
  fonts,
  image: { resourceId: images[0][0], path: 'public/prototype/sets.png', width: images[0][1].data.readUInt32BE(16), height: images[0][1].data.readUInt32BE(20) },
  externalFontLicenseSources: {
    Manrope: 'https://raw.githubusercontent.com/google/fonts/main/ofl/manrope/OFL.txt',
    'IBM Plex Mono': 'https://raw.githubusercontent.com/google/fonts/main/ofl/ibmplexmono/OFL.txt',
  },
}));

const tokenFile = JSON.parse(await readFile(resolve(root, 'design/systems/nsp/tokens.json'), 'utf8'));
const tokenLines = Object.entries(tokenFile.tokens).map(([name, token]) => {
  assert.match(name, /^[a-z][a-z\d-]*$/);
  assert.equal(typeof token.value, 'string');
  assert(!/[;{}]/.test(token.value), 'Invalid CSS token value');
  assert(['prototype', 'extension'].includes(token.origin), `Missing provenance for ${name}`);
  if (token.type === 'color' && token.origin === 'prototype') {
    assert(template.includes(token.value), `${name} is not a literal color from the source`);
  }
  for (const match of token.value.matchAll(/var\(--([a-z\d-]+)\)/g)) {
    assert(tokenFile.tokens[match[1]], `${name} references an undefined token`);
  }
  return `  --${name}: ${token.value};`;
});
output.set('design/systems/nsp/tokens.css', `/* Generated from tokens.json by scripts/extract-prototype.mjs. */\n:root {\n${tokenLines.join('\n')}\n}\n`);
const primitiveCss = await readFile(resolve(root, 'packages/presentation/design-system.css'), 'utf8');
for (const match of primitiveCss.matchAll(/var\(--([a-z\d-]+)\)/g)) {
  assert(tokenFile.tokens[match[1]], `Primitive CSS references undefined --${match[1]}`);
}

for (const [path, data] of output) {
  const expected = Buffer.isBuffer(data) ? data : Buffer.from(data);
  if (check) {
    assert((await readFile(resolve(root, path))).equals(expected), `${path} differs; rerun extraction`);
  } else {
    await mkdir(dirname(resolve(root, path)), { recursive: true });
    await writeFile(resolve(root, path), expected);
  }
}
assert((await readFile(resolve(root, inputPath))).equals(bytes), 'Input prototype changed during extraction');
console.log(`${check ? 'Verified' : 'Extracted'} ${output.size} artifacts, ${fonts.length} local font subsets and 1 image; source SHA-256 ${sha256(bytes)}`);
