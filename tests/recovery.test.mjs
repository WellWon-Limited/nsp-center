import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,readFile,writeFile,stat} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {randomUUID} from 'node:crypto';
import {execFile} from 'node:child_process';
import {promisify,parseEnv} from 'node:util';
import pg from 'pg';
import {migrateDatabase} from '../apps/api/database/migrate.mjs';
import {backupDatabase,databaseFingerprint} from '../apps/api/database/backup.mjs';
import {recoverDatabase} from '../apps/api/database/recover.mjs';
import {saveCheckout} from '../apps/api/order-checkout.mjs';
import {hashPassword} from '../apps/api/accounts.mjs';
import {launch} from './server-helper.mjs';
const exec=promisify(execFile),root=fileURLToPath(new URL('../',import.meta.url));

test('disaster rehearsal: restore synthetic orders to a clean cluster, recreate roles and run website',
 {skip:!process.env.NSP_TEST_BACKUP?'Requires PostgreSQL 18 client tools (NSP_TEST_BACKUP=1)':process.getuid?.()===0&&'Postgres does not run as root',timeout:90000},async t=>{
 const {default:EmbeddedPostgres}=await import('embedded-postgres');
 const dir=await mkdtemp(join(tmpdir(),'nsp-recovery-'));
 const port=20000+Math.floor(Math.random()*18000);
 const source=new EmbeddedPostgres({databaseDir:join(dir,'source'),port,user:'source_owner',password:'source-test',persistent:false,autoRehydrateSymlinks:true,onLog:()=>{},onError:()=>{}});
 const target=new EmbeddedPostgres({databaseDir:join(dir,'target'),port:port+1,user:'new_owner',password:'new-test',persistent:false,autoRehydrateSymlinks:true,onLog:()=>{},onError:()=>{}});
 let sourcePool,targetPool,api,web,sourceStarted=false,targetStarted=false;
 t.after(async()=>{await web?.stop();await api?.stop();await sourcePool?.end();await targetPool?.end();if(sourceStarted)await source.stop();if(targetStarted)await target.stop();await rm(dir,{recursive:true,force:true});});
 await source.initialise();await source.start();sourceStarted=true;await source.createDatabase('source_store');
 const sourceUrl=`postgres://source_owner:source-test@127.0.0.1:${port}/source_store`;
 const targetUrl=`postgres://new_owner:new-test@127.0.0.1:${port+1}/restored_store`;
 sourcePool=new pg.Pool({connectionString:sourceUrl});
 const content=JSON.parse(await readFile(join(root,'packages/catalog/generated/content.json'),'utf8'));
 await migrateDatabase(sourcePool,{products:content.products,themes:content.themes,pickupAddress:content.site.address});
 const password='Recovery-test-password-2026';
 const {rows:[customer]}=await sourcePool.query("insert into users(email,first_name,last_name,password_hash,consent_at) values('restore@example.ru','Тест','Покупатель',$1,now()) returning *",[await hashPassword(password)]);
 await sourcePool.query("insert into users(email,first_name,last_name,password_hash,consent_at,role) values('staff-restore@example.ru','Тест','Сотрудник',$1,now(),'admin')",[await hashPassword(password)]);
 const product=content.products.find(p=>p.prices?.retail>0&&p.availability==='InStock');
 const body={key:randomUUID(),items:[{id:product.id,quantity:1}],expectedSubtotalKopecks:product.prices.retail*100,form:{firstName:'Тест',lastName:'Покупатель',email:'restore@example.ru',phone:'+7 900 111-22-33',method:'pickup',comment:'',offer:true,consent:true}};
 const saved=await saveCheckout({pool:sourcePool,buildRate:content.pricing.rubPerUnit,pickupAddress:content.site.address,loadCatalog:async()=>({products:[product],settings:{products:{},cards:{}}})},customer,body);
 const original=await databaseFingerprint(sourcePool);
 const dump=await backupDatabase(sourceUrl,{directory:join(dir,'synthetic-backups')});
 await target.initialise();await target.start();targetStarted=true;await target.createDatabase('restored_store');
 targetPool=new pg.Pool({connectionString:targetUrl});
 // Corruption must be rejected before any objects or roles are created.
 await writeFile(dump.file+'.json',JSON.stringify({...dump,sha256:'0'.repeat(64)}));
 await assert.rejects(recoverDatabase({targetUrl,file:dump.file}),/checksum mismatch/);
 assert.equal((await targetPool.query("select count(*)::int n from pg_tables where schemaname='public'")).rows[0].n,0);
 await writeFile(dump.file+'.json',JSON.stringify(dump));
 const credentials=join(dir,'recovered.env');
 const result=await exec(process.execPath,['scripts/restore-db.mjs',dump.file],{cwd:root,env:{...process.env,RESTORE_DATABASE_URL:targetUrl,RESTORE_APP_ENV:credentials}});
 assert.match(result.stdout,/Restored and verified/);
 const appUrl=parseEnv(await readFile(credentials,'utf8')).DATABASE_URL;
 assert.equal((await stat(credentials)).mode&0o777,0o600);
 assert.ok(!result.stdout.includes(new URL(appUrl).password));
 assert.deepEqual(await databaseFingerprint(targetPool),original);
 assert.deepEqual(await databaseFingerprint(sourcePool),original);
 assert.deepEqual((await targetPool.query("select rolsuper,rolcreatedb,rolcreaterole from pg_roles where rolname='nsp_app'")).rows[0],{rolsuper:false,rolcreatedb:false,rolcreaterole:false});
 await assert.rejects(recoverDatabase({targetUrl,file:dump.file}),/empty database/);
 api=await launch('apps/api/server.mjs',root,{DATABASE_URL:appUrl});
 web=await launch('apps/web/server.mjs',root,{API_ORIGIN:api.origin});
 const call=async(path,{method='GET',body,cookie=''}={})=>{
  const r=await fetch(web.origin+path,{method,headers:{Origin:web.origin,Cookie:cookie,'Content-Type':'application/json'},body:body?JSON.stringify(body):undefined});
  return {status:r.status,body:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]??''};
 };
 assert.equal((await fetch(web.origin+'/catalog/')).status,200);
 const signed=await call('/api/auth/login',{method:'POST',body:{login:'restore@example.ru',password}});
 assert.equal(signed.status,200);assert.ok(signed.cookie);
 const mine=await call('/api/account/orders',{cookie:signed.cookie});
 assert.equal(mine.status,200);assert.equal(mine.body.orders[0].id,saved.order.id);assert.equal(mine.body.orders[0].total,saved.order.total);
 const staff=await call('/api/admin/login',{method:'POST',body:{login:'staff-restore@example.ru',password}});
 assert.equal(staff.status,200);
 const orders=await call('/api/admin/orders',{cookie:staff.cookie});
 const order=orders.body.orders[0];
 const changed=await call('/api/admin/orders',{method:'PUT',cookie:staff.cookie,body:{id:order.id,updatedAt:order.updatedAt,status:'processing',note:''}});
 assert.equal(changed.status,200,JSON.stringify(changed.body));assert.equal(changed.body.order.history.length,2);
 const next=await call('/api/orders',{method:'POST',cookie:signed.cookie,body:{...body,key:randomUUID()}});
 assert.equal(next.status,201,JSON.stringify(next.body));assert.ok(Number(next.body.order.id)>Number(saved.order.id),'restored sequences generate new IDs');
 // SIGQUIT requests immediate shutdown (no checkpoint); restart must replay WAL.
 const committed=await databaseFingerprint(targetPool);
 await web.stop();web=null;await api.stop();api=null;
 await targetPool.end();targetPool=null;
 const exited=new Promise(resolve=>target.process.once('exit',resolve));
 target.process.kill('SIGQUIT');await exited;targetStarted=false;
 await target.start();targetStarted=true;
 targetPool=new pg.Pool({connectionString:targetUrl});
 assert.deepEqual(await databaseFingerprint(targetPool),committed,'acknowledged data survives immediate database shutdown');
 assert.deepEqual(await databaseFingerprint(sourcePool),original,'all rehearsal mutations stayed on the restored cluster');
});
