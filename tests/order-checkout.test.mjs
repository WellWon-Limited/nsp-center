const request = (extra = {}) => ({ key: randomUUID(), guestToken:randomBytes(32).toString('hex'), items: [{ id: 'test-product', quantity: 2 }], expectedSubtotalKopecks: 200000, form: { firstName:'Тест',lastName:'Покупатель',phone:'+7 900 000-00-00',email:'order-test@example.ru',method:'pickup',city:'Санкт-Петербург',comment:'Тестовый заказ',offer:true,consent:true,mailing:false }, ...extra });
test('checkout validates quantities, contacts, consents and request identity', () => {
  assert.equal(checkoutInput(request()).items[0].quantity, 2);
  for (const body of [request({key:'123'}),request({items:[]}),request({items:[{id:'test-product',quantity:0}]}),request({items:[{id:'test-product',quantity:1.5}]}),request({expectedSubtotalKopecks:NaN}),request({form:{...request().form,consent:false}}),request({items:[{id:'test-product',quantity:1},{id:'test-product',quantity:1}]})]) assert.throws(()=>checkoutInput(body));
});

test('orders persist atomically, retry safely, enforce prices and preserve private history', {skip:process.getuid?.()===0&&'Postgres does not run as root'}, async t => {
  const {default:EmbeddedPostgres}=await import('embedded-postgres');
  const dir=mkdtempSync(join(tmpdir(),'nsp-order-test-'));
  const port=20000+Math.floor(Math.random()*20000);
  const pg=new EmbeddedPostgres({databaseDir:join(dir,'db'),port,user:'test',password:'test',persistent:false,autoRehydrateSymlinks:true,onLog:()=>{},onError:()=>{}});
  await pg.initialise(); await pg.start(); await pg.createDatabase('orders');
  const product={id:'test-product',name:'Тестовый товар',article:'TEST-1',availability:'InStock',prices:{retail:1000,partner:800}};
  const accounts=await createAccounts({databaseUrl:`postgres://test:test@127.0.0.1:${port}/orders`,cardProducts:[product],cbr:false,buildRate:100,pickupAddress:'Тестовый адрес самовывоза'});
  const server=createServer((req,res)=>accounts.handle(req,res,new URL(req.url,'http://localhost')));
  await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  t.after(async()=>{await new Promise(resolve=>server.close(resolve));await accounts.close();await pg.stop();rmSync(dir,{recursive:true,force:true});});
  const base=`http://127.0.0.1:${server.address().port}`;
  const call=async(path,method='GET',body,cookie='',headers={})=>{
    const r=await fetch(base+path,{method,headers:{'Content-Type':'application/json',Cookie:cookie,...headers},body:body?JSON.stringify(body):undefined});
    return {status:r.status,body:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]??''};
  };
  const reg=await call('/api/auth/register','POST',{firstName:'Тест',lastName:'Покупатель',email:'order-test@example.ru',password:'test-password-123',consent:true});
  assert.equal(reg.status,201); const cookie=reg.cookie;
  const input=request();
  const [a,b]=await Promise.all([call('/api/orders','POST',input,cookie),call('/api/orders','POST',input,cookie)]);
  assert.deepEqual([a.status,b.status].sort(),[200,201]);
  assert.equal(a.body.order.id,b.body.order.id); const id=a.body.order.id;
  assert.equal(a.body.order.paid,false);assert.equal(a.body.order.paymentStatus,'not_connected');
  assert.equal((await accounts.pool.query('select count(*)::int n from order_items where order_id=$1',[id])).rows[0].n,1);
  assert.equal((await accounts.pool.query('select count(*)::int n from order_events where order_id=$1',[id])).rows[0].n,1);
  const saved=(await accounts.pool.query('select * from shop_orders where id=$1',[id])).rows[0];
  assert.equal(Number(saved.total_kopecks),200000);assert.equal('total' in saved,false);assert.equal('items' in saved,false);assert.equal(saved.delivery.pickupAddress,'Тестовый адрес самовывоза');
  assert.equal(saved.consents.mailing,false);
  const mismatch=await call('/api/orders','POST',{...input,form:{...input.form,comment:'Изменено'}},cookie);
  assert.equal(mismatch.status,409);
  assert.equal((await call('/api/orders','POST',input,'')).status,409,'another account/guest cannot retrieve a private replay');
  product.name='Новое название';product.prices.retail=1200;
  const replay=await call('/api/orders','POST',input,cookie);
  assert.equal(replay.status,200);assert.equal(replay.body.order.items[0].name,'Тестовый товар');assert.equal(replay.body.order.total,2000);
  assert.equal((await call('/api/orders','POST',request(),cookie)).status,409,'server rejects stale price');
  assert.equal((await call('/api/orders','POST',request({items:[{id:'missing',quantity:1}]}),cookie)).status,409);
  product.availability='OutOfStock';assert.equal((await call('/api/orders','POST',request(),cookie)).status,409);product.availability='InStock';
  assert.equal((await call('/api/orders','POST',request(),cookie,{Origin:'https://other.example'})).status,403);
  const guestInput=request({expectedSubtotalKopecks:240000});
  const guest=await call('/api/orders','POST',guestInput);
  assert.equal(guest.status,201);
  assert.equal((await accounts.pool.query('select user_id from shop_orders where id=$1',[guest.body.order.id])).rows[0].user_id,null,'email does not attach a guest order to an account');
  const mine=await call('/api/account/orders','GET',null,cookie);
  assert.equal(mine.body.orders.length,1);assert.equal(mine.body.orders[0].id,id);assert.equal('customer' in mine.body.orders[0],false);
  const cdek=await call('/api/orders','POST',request({expectedSubtotalKopecks:240000,form:{...input.form,method:'cdek',cdekPoint:'Тестовый пункт',cdekPrice:1}}),cookie);
  assert.equal(cdek.status,201);assert.equal(cdek.body.order.deliveryPrice,null);assert.equal(cdek.body.order.delivery.priceStatus,'requires_quote');
  const forgedCard=await call('/api/orders','POST',request({expectedSubtotalKopecks:160000,partnerId:'123',card:true}),cookie);
  assert.equal(forgedCard.status,409,'browser cannot choose the card price');
  await accounts.pool.query("update users set partner_id='123456' where email='order-test@example.ru'");
  assert.equal((await call('/api/orders','POST',request({expectedSubtotalKopecks:160000}),cookie)).status,201,'server account controls card entitlement');
  // A failure halfway through must leave neither the order nor its history behind.
  await accounts.pool.query(`create function reject_test_line() returns trigger language plpgsql as $$ begin raise exception 'test line failure'; end $$; create trigger reject_test_line before insert on order_items for each row execute function reject_test_line()`);
  const failed=request({expectedSubtotalKopecks:160000});
  assert.equal((await call('/api/orders','POST',failed,cookie)).status,500);
  assert.equal((await accounts.pool.query('select count(*)::int n from shop_orders where checkout_key=$1',[failed.key])).rows[0].n,0);
  await accounts.pool.query('drop trigger reject_test_line on order_items');
  assert.equal((await call('/api/orders','POST',failed,cookie)).status,201,'retry after rollback can succeed');
  await accounts.pool.query("insert into users(email,first_name,last_name,password_hash,role,consent_at) values('order-staff@example.ru','Тест','Сотрудник',$1,'admin',now())",[await hashPassword('staff-password-123')]);
  const staff=await call('/api/admin/login','POST',{login:'order-staff@example.ru',password:'staff-password-123'});
  assert.equal(staff.status,200);
  const admin=await call('/api/admin/orders','GET',null,staff.cookie);
  const order=admin.body.orders.find(o=>o.id===id);
  assert.equal(order.history.length,1);
  const update={id,status:'processing',note:'Служебный комментарий',updatedAt:order.updatedAt};
  const changed=await call('/api/admin/orders','PUT',update,staff.cookie);
  assert.equal(changed.status,200,JSON.stringify(changed.body));
  assert.equal((await call('/api/admin/orders','PUT',update,staff.cookie)).status,409);
  const events=(await accounts.pool.query('select * from order_events where order_id=$1 order by id',[id])).rows;
  assert.equal(events.length,3);assert.equal(events[1].from_status,'new');assert.equal(events[1].to_status,'processing');assert.equal(events[1].actor_role,'admin');
  const after=(await call('/api/account/orders','GET',null,cookie)).body.orders.find(o=>o.id===id);
  assert.equal(after.status,'processing');assert.equal('note' in after,false);
  // Persistent pages authorize every read, including owner/guest separation and staff cookies.
  assert.equal((await call(`/api/orders/${id}`,'GET',null,cookie)).status,200);
  assert.equal((await call(`/api/orders/${id}`)).status,404);
  assert.equal((await call(`/api/orders/${id}`,'GET',null,staff.cookie)).status,404);
  const other=await call('/api/auth/register','POST',{firstName:'Другой',lastName:'Покупатель',email:'other-order@example.ru',password:'test-password-123',consent:true});
  assert.equal((await call(`/api/orders/${id}`,'GET',null,other.cookie)).status,404);
  const guestPath=`/api/orders/${guest.body.order.id}`;
  assert.equal((await call(guestPath)).status,404);
  assert.equal((await call(guestPath,'GET',null,cookie)).status,404);
  assert.equal((await call(guestPath,'GET',null,'',{Authorization:`Bearer ${randomBytes(32).toString('hex')}`})).status,404);
  const authorized=await call(guestPath,'GET',null,'',{Authorization:`Bearer ${guestInput.guestToken}`});
  assert.equal(authorized.status,200);assert.equal(authorized.body.order.items.length,1);
  assert.equal('guest_token_hash' in authorized.body.order,false);assert.equal('note' in authorized.body.order,false);
  assert.ok(guest.body.orderUrl.endsWith('#access='+guestInput.guestToken));
  const guestAgain=await call('/api/orders','POST',guestInput);
  assert.equal(guestAgain.body.orderUrl,guest.body.orderUrl,'lost create response keeps the same guest link');
  assert.equal((await call(`/api/orders/${id}`,'GET',null,'',{Authorization:`Bearer ${guestInput.guestToken}`})).status,404);
  // Reject illegal transitions; allow a reasoned correction without rewriting previous events.
  const change={id,status:'new',note:changed.body.order.note,updatedAt:changed.body.order.updatedAt};
  assert.equal((await call('/api/admin/orders','PUT',change,staff.cookie)).status,400);
  assert.equal((await call('/api/admin/orders','PUT',{...change,correction:true},staff.cookie)).status,400);
  const corrected=await call('/api/admin/orders','PUT',{...change,correction:true,reason:'Статус изменили ошибочно'},staff.cookie);
  assert.equal(corrected.status,200);
  assert.equal(corrected.body.order.history.at(-1).correction,true);
  assert.equal(corrected.body.order.history.at(-1).reason,'Статус изменили ошибочно');
  const competing={id,status:'processing',note:'Повторная сборка',updatedAt:corrected.body.order.updatedAt};
  const raced=await Promise.all([call('/api/admin/orders','PUT',competing,staff.cookie),call('/api/admin/orders','PUT',competing,staff.cookie)]);
  assert.deepEqual(raced.map(r=>r.status).sort(),[200,409],'only one staff member can change an opened version');
  const exposed=(await call(`/api/orders/${id}`,'GET',null,cookie)).body.order;
  assert.equal(exposed.history.some(e=>'reason' in e||e.type==='note_changed'),false,'internal explanations stay private');
  // The database itself must reject inconsistent totals, even if code forgets validation.
  await assert.rejects(accounts.pool.query('update shop_orders set total_kopecks=total_kopecks+1 where id=$1',[id]),e=>e.code==='23514');
  await assert.rejects(accounts.pool.query('update order_items set unit_price_kopecks=unit_price_kopecks-1,line_total_kopecks=line_total_kopecks-quantity where order_id=$1',[id]),e=>e.code==='23514');
  await assert.rejects(accounts.pool.query('delete from order_items where order_id=$1',[id]),e=>e.code==='23514');
  const preserved=(await accounts.pool.query('select total_kopecks from shop_orders where id=$1',[id])).rows[0];
  assert.equal(Number(preserved.total_kopecks),200000);
  // Migrate a pre-normalization order in an isolated schema, preserving its historical prices.
  const migrationClient=await accounts.pool.connect();
  try {
    await migrationClient.query('begin');
    await migrationClient.query('create schema legacy_order_test; set local search_path to legacy_order_test');
    await migrationClient.query('create table users(id bigint primary key)');
    await migrationClient.query(`create table shop_orders(id bigserial primary key,user_id bigint references users(id),customer jsonb not null,items jsonb not null,total integer not null,status text not null default 'new',note text not null default '',created_at timestamptz default now(),updated_at timestamptz default now());
      insert into shop_orders(customer,items,total) values('{}','[{"id":"old","name":"Старое название","quantity":2,"price":500}]',1350)`);
    await migrationClient.query(ORDER_SCHEMA);
    const {rows:[migrated]}=await migrationClient.query('select * from order_read');
    assert.equal(Number(migrated.total_kopecks),135000);
    assert.equal(Number(migrated.delivery_kopecks),35000);
    assert.equal(migrated.items[0].name,'Старое название');
    assert.equal(migrated.items[0].price,500);
    await migrationClient.query(ORDER_SCHEMA);
    assert.equal((await migrationClient.query('select count(*)::int n from order_items')).rows[0].n,1);
    await migrationClient.query('rollback');
  } finally { await migrationClient.query('rollback');migrationClient.release(); }
  const reopened=await createAccounts({pool:accounts.pool,cardProducts:[product],cbr:false,pickupAddress:'Новый адрес магазина'});
  await reopened.ready();
  const snapshot=(await accounts.pool.query('select delivery from shop_orders where id=$1',[id])).rows[0].delivery;
  assert.equal(snapshot.pickupAddress,'Тестовый адрес самовывоза','restart and address change preserve old snapshot');

});
